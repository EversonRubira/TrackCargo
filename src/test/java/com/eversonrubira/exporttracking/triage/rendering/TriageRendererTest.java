package com.eversonrubira.exporttracking.triage.rendering;

import com.eversonrubira.exporttracking.triage.provider.FailureReason;
import com.eversonrubira.exporttracking.triage.provider.ProviderOutcome;
import com.eversonrubira.exporttracking.triage.security.SecretFilter;
import com.eversonrubira.exporttracking.triage.validation.Diagnosis;
import com.eversonrubira.exporttracking.triage.validation.DiagnosisValidator;
import com.eversonrubira.exporttracking.triage.validation.SampleDiagnosis;
import org.junit.jupiter.api.Test;

import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

// T09: o bloco AI TEST TRIAGE e legivel, nao afirma factos e nao deixa o modelo injetar comandos no log.
class TriageRendererTest {

    static final String API_KEY = "sk-" + "ant-api03-" + "TestKeyTestKeyTestKey1234";
    static final String DB_PASSWORD = "p4ss-" + "w0rd-" + "X7";
    static final String TEST_ID = "com.acme.shop.OrderServiceTest#shipsOrder";

    private final TriageRenderer renderer = new TriageRenderer(new SecretFilter(Map.of("ANTHROPIC_API_KEY", API_KEY)));

    private static Diagnosis diagnosis(Map<String, Object> json) {
        var result = DiagnosisValidator.validate(SampleDiagnosis.json(json));
        assertTrue(result.isValid(), result.errors().toString());
        return result.diagnosis();
    }

    // ---------- snapshots ----------

    @Test
    void successSnapshot() {
        String expected = """
                | ==================== AI TEST TRIAGE ====================
                | Test: com.acme.shop.OrderServiceTest#shipsOrder
                | Generated by an AI model from the failure and the project docs. Treat it as a hypothesis, not a fact.
                | The original test failure is unchanged; fixes and design decisions stay with you.
                |
                | Probable cause (hypothesis):
                |   ship() does not validate the current state
                |
                | Evidence:
                |   - expected SHIPPED but was CREATED
                |   - OrderService.java:14
                |
                | Related documents:
                |   - docs/SPEC.md
                |
                | Possible solutions:
                |   1. Check the state transition guard in OrderService.ship
                |      Trade-offs:
                |        - Touches shared state-machine code
                |
                | Confidence: MEDIUM
                |   Reason: stack trace points to one class, no log from the call
                |
                | Limitations:
                |   - no application log available
                | ==================== END AI TEST TRIAGE ====================
                """;
        assertEquals(expected, renderer.success(TEST_ID, diagnosis(SampleDiagnosis.valid())));
    }

    @Test
    void triageFailedSnapshotKeepsTheOriginalFailureVisible() {
        ProviderOutcome outcome = new ProviderOutcome(null, FailureReason.TIMEOUT, "no response within 30 s", 2, 61000, -1, -1);
        String expected = """
                | ==================== AI TEST TRIAGE ====================
                | TRIAGE FAILED
                | Test: com.acme.shop.OrderServiceTest#shipsOrder
                | Reason: The AI provider did not answer in time.
                | Detail: no response within 30 s
                | Provider attempts: 2
                | The original test failure is unchanged and still decides the build result. Only the AI analysis is missing.
                | ==================== END AI TEST TRIAGE ====================
                """;
        assertEquals(expected, renderer.failure(TEST_ID, outcome));
    }

    @Test
    void emptyOptionalSectionsSayTheyAreEmptyInsteadOfDisappearing() {
        Map<String, Object> json = SampleDiagnosis.valid();
        json.put("relatedDocuments", List.of());
        json.put("limitations", List.of());
        String text = renderer.success(TEST_ID, diagnosis(json));
        assertTrue(text.contains("Related documents:\n|   none found\n"), text);
        assertTrue(text.contains("Limitations:\n|   none reported\n"), text);
    }

    @Test
    void confidenceIsALevelWithAReasonNeverAPercentage() {
        for (String level : List.of("HIGH", "MEDIUM", "LOW")) {
            Map<String, Object> json = SampleDiagnosis.valid();
            json.put("confidence", level);
            String text = renderer.success(TEST_ID, diagnosis(json));
            assertTrue(text.contains("| Confidence: " + level + "\n|   Reason: "), text);
            assertFalse(text.contains("%"), text);
        }
    }

    @Test
    void theHypothesisAndHumanDecisionWordingIsAlwaysPresent() {
        String text = renderer.success(TEST_ID, diagnosis(SampleDiagnosis.valid()));
        assertTrue(text.contains("hypothesis, not a fact"));
        assertTrue(text.contains("stay with you"));
        assertTrue(text.contains("The original test failure is unchanged"));
    }

    // ---------- injecao de comandos no log do Actions ----------

    static final List<String> HOSTILE = List.of(
            "::error::build is compromised",
            "##[error]fake failure",
            "::add-mask::secret",
            "::set-output name=x::y",
            "  ::warning::indented still counts after the runner trims it",
            "first line\n::stop-commands::token\nthird",
            "windows\r\n##[group]evil\r\nend",
            "old mac\r::error::x",
            "unicode separator ::error::y ##[error]z\u0085::warning::w");

    private static void assertNoWorkflowCommand(String rendered) {
        for (String line : rendered.split("\n", -1)) {
            if (line.isEmpty()) {
                continue;
            }
            assertTrue(line.startsWith("|"), "line without prefix: [" + line + "]");
            String trimmed = line.stripLeading();
            assertFalse(trimmed.startsWith("::"), "workflow command: [" + line + "]");
            assertFalse(trimmed.startsWith("##["), "workflow command: [" + line + "]");
        }
    }

    @Test
    void noFieldOfASuccessfulDiagnosisCanInjectAWorkflowCommand() {
        for (String hostile : HOSTILE) {
            Map<String, Object> json = SampleDiagnosis.valid();
            json.put("probableCause", hostile);
            json.put("evidence", List.of(hostile, "ok"));
            json.put("relatedDocuments", List.of(hostile));
            json.put("possibleSolutions", List.of(Map.of("solution", hostile, "tradeoffs", List.of(hostile))));
            json.put("confidenceReason", hostile);
            json.put("limitations", List.of(hostile));
            assertNoWorkflowCommand(renderer.success(hostile, diagnosis(json)));
        }
    }

    @Test
    void noFieldOfAFailureBlockCanInjectAWorkflowCommand() {
        for (String hostile : HOSTILE) {
            assertNoWorkflowCommand(renderer.failure(hostile, hostile, hostile, 1));
            assertNoWorkflowCommand(renderer.failure(hostile,
                    new ProviderOutcome(null, FailureReason.INVALID_RESPONSE, hostile, 2, 1, -1, -1)));
        }
    }

    @Test
    void multilineTextKeepsItsLinesButEveryOneIsPrefixed() {
        Map<String, Object> json = SampleDiagnosis.valid();
        json.put("probableCause", "line one\nline two\r\nline three");
        String text = renderer.success(TEST_ID, diagnosis(json));
        assertTrue(text.contains("|   line one\n|   line two\n|   line three\n"), text);

        json.put("probableCause", "old mac one\rold mac two");
        assertTrue(renderer.success(TEST_ID, diagnosis(json)).contains("|   old mac one\n|   old mac two\n"));
    }

    // ---------- limpeza de caracteres ----------

    @Test
    void controlAndInvisibleCharactersAreRemoved() {
        String dirty = "red\u001B[31mtext\u0000\u0007 bidi‮evil zero​width bom﻿ tab\tend";
        Map<String, Object> json = SampleDiagnosis.valid();
        json.put("probableCause", dirty);
        String text = renderer.success(TEST_ID, diagnosis(json));
        text.codePoints().forEach(cp -> {
            if (cp == '\n') {
                return;
            }
            int type = Character.getType(cp);
            assertTrue(type != Character.CONTROL && type != Character.FORMAT,
                    "invisible/control character U+" + Integer.toHexString(cp) + " reached the log");
        });
        assertTrue(text.contains("red[31mtext bidievil zerowidth bom tab  end"), text);
    }

    @Test
    void ordinaryUnicodeSurvives() {
        Map<String, Object> json = SampleDiagnosis.valid();
        json.put("probableCause", "Senha curta: validação falhou em 'pedido' → estado inválido ✓");
        assertTrue(renderer.success(TEST_ID, diagnosis(json)).contains("Senha curta: validação falhou em 'pedido' → estado inválido ✓"));
    }

    // ---------- segredos ----------

    @Test
    void secretsAreMaskedInEveryPartOfBothBlocks() {
        Map<String, Object> json = SampleDiagnosis.valid();
        json.put("probableCause", "key " + API_KEY + " was used");
        json.put("evidence", List.of("spring.datasource.password=" + DB_PASSWORD));
        json.put("confidenceReason", "saw " + API_KEY);
        String success = renderer.success("test " + API_KEY, diagnosis(json));
        String failure = renderer.failure("test", "reason " + API_KEY, "detail password=" + DB_PASSWORD, 1);
        for (String text : List.of(success, failure)) {
            assertFalse(text.contains(API_KEY), text);
            assertFalse(text.contains(DB_PASSWORD), text);
            assertTrue(text.contains(SecretFilter.MASK), text);
        }
    }

    @Test
    void aSecretCannotHideFromTheFilterBehindAnInvisibleCharacter() {
        String split = API_KEY.substring(0, 12) + "​" + API_KEY.substring(12);
        Map<String, Object> json = SampleDiagnosis.valid();
        json.put("probableCause", "hidden " + split);
        String text = renderer.success(TEST_ID, diagnosis(json));
        assertFalse(text.contains(API_KEY.substring(12)), text);
        assertTrue(text.contains(SecretFilter.MASK), text);
    }

    // ---------- razoes operacionais ----------

    @Test
    void everyFailureReasonHasADistinctReadableExplanation() {
        Set<String> seen = new HashSet<>();
        for (FailureReason reason : FailureReason.values()) {
            String text = TriageRenderer.operationalReason(reason);
            assertTrue(text.endsWith("."), reason + " -> " + text);
            assertTrue(seen.add(text), "duplicate explanation for " + reason);
            String block = renderer.failure(TEST_ID, new ProviderOutcome(null, reason, "d", 1, 1, -1, -1));
            assertTrue(block.contains("| TRIAGE FAILED\n"), block);
            assertTrue(block.contains("| Reason: " + text + "\n"), block);
        }
    }
}
