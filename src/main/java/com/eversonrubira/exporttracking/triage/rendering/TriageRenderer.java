package com.eversonrubira.exporttracking.triage.rendering;

import com.eversonrubira.exporttracking.triage.provider.FailureReason;
import com.eversonrubira.exporttracking.triage.provider.ProviderOutcome;
import com.eversonrubira.exporttracking.triage.security.SecretFilter;
import com.eversonrubira.exporttracking.triage.validation.Diagnosis;

import java.util.ArrayList;
import java.util.List;

/**
 * Renderer do bloco {@code AI TEST TRIAGE} para o log do GitHub Actions (T09, RF-06).
 *
 * O texto do diagnostico vem de um modelo que leu dados nao confiaveis, e o log do Actions
 * interpreta algumas linhas como comandos. Por isso todo o texto passa por tres defesas:
 *  1. caracteres de controlo e de formatacao invisivel (ESC, bidi, zero-width) sao removidos;
 *  2. segredos conhecidos sao mascarados DEPOIS da limpeza (um zero-width dentro de uma chave
 *     nao a pode esconder do filtro);
 *  3. TODA a linha comeca por "| ". O runner ignora espacos iniciais mas reconhece "::cmd::" e
 *     "##[cmd]" no inicio da linha; com o prefixo nenhuma linha escrita por nos o e.
 *
 * Nunca afirma o diagnostico como facto (RF-05) e lembra que a decisao e humana (RF-07).
 * Nao toca no resultado dos testes (RF-08): so devolve texto.
 */
public final class TriageRenderer {

    public static final String TITLE = "AI TEST TRIAGE";
    public static final String FAILED = "TRIAGE FAILED";

    static final String PREFIX = "| ";
    private static final String RULE = "=".repeat(20);

    private final SecretFilter filter;

    public TriageRenderer(SecretFilter filter) {
        this.filter = filter;
    }

    public String success(String testId, Diagnosis d) {
        Lines out = new Lines();
        out.header();
        out.line("", "Test: " + testId);
        out.line("", "Generated by an AI model from the failure and the project docs. Treat it as a hypothesis, not a fact.");
        out.line("", "The original test failure is unchanged; fixes and design decisions stay with you.");
        out.blank();
        out.line("", "Probable cause (hypothesis):");
        out.line("  ", d.probableCause());
        out.blank();
        out.line("", "Evidence:");
        out.bullets(d.evidence(), "none");
        out.blank();
        out.line("", "Related documents:");
        out.bullets(d.relatedDocuments(), "none found");
        out.blank();
        out.line("", "Possible solutions:");
        int n = 1;
        for (Diagnosis.Solution s : d.possibleSolutions()) {
            out.line("  ", n++ + ". " + s.solution());
            out.line("     ", "Trade-offs:");
            for (String t : s.tradeoffs()) {
                out.line("       ", "- " + t);
            }
        }
        out.blank();
        out.line("", "Confidence: " + d.confidence().name());
        out.line("  ", "Reason: " + d.confidenceReason());
        out.blank();
        out.line("", "Limitations:");
        out.bullets(d.limitations(), "none reported");
        out.footer();
        return out.text();
    }

    public String failure(String testId, ProviderOutcome outcome) {
        return failure(testId, operationalReason(outcome.reason()), outcome.detail(), outcome.attempts());
    }

    /** Falha do triage por qualquer causa operacional (provider, log em falta, limite, ...). */
    public String failure(String testId, String operationalReason, String detail, int attempts) {
        Lines out = new Lines();
        out.header();
        out.line("", FAILED);
        out.line("", "Test: " + testId);
        out.line("", "Reason: " + operationalReason);
        out.line("", "Detail: " + detail);
        out.line("", "Provider attempts: " + attempts);
        out.line("", "The original test failure is unchanged and still decides the build result. Only the AI analysis is missing.");
        out.footer();
        return out.text();
    }

    static String operationalReason(FailureReason reason) {
        return switch (reason) {
            case PROVIDER_ERROR -> "The AI provider returned an error or could not be reached.";
            case TIMEOUT -> "The AI provider did not answer in time.";
            case INVALID_RESPONSE -> "The AI provider's answer did not meet the diagnosis contract.";
            case MISSING_API_KEY -> "No API key is configured for the AI provider.";
            case INVALID_CREDENTIALS -> "The AI provider rejected the credentials.";
            case REQUEST_REJECTED -> "The AI provider rejected the request.";
            case INTERRUPTED -> "The triage was interrupted.";
        };
    }

    /** Remove controlo/invisiveis, normaliza quebras de linha e mascara segredos. */
    String clean(String text) {
        String value = text == null ? "" : text;
        StringBuilder sb = new StringBuilder(value.length());
        int i = 0;
        while (i < value.length()) {
            int cp = value.codePointAt(i);
            i += Character.charCount(cp);
            if (cp == '\r') {
                if (i < value.length() && value.charAt(i) == '\n') {
                    i++;
                }
                sb.append('\n');
            } else if (cp == '\n' || cp == 0x85 || cp == 0x2028 || cp == 0x2029) {
                sb.append('\n');
            } else if (cp == '\t') {
                sb.append("  ");
            } else {
                int type = Character.getType(cp);
                if (type != Character.CONTROL && type != Character.FORMAT && type != Character.UNASSIGNED
                        && type != Character.SURROGATE && type != Character.PRIVATE_USE) {
                    sb.appendCodePoint(cp);
                }
            }
        }
        return filter.mask(sb.toString());
    }

    private final class Lines {
        private final List<String> lines = new ArrayList<>();

        void header() {
            lines.add(PREFIX + RULE + " " + TITLE + " " + RULE);
        }

        void footer() {
            lines.add(PREFIX + RULE + " END " + TITLE + " " + RULE);
        }

        void blank() {
            lines.add("|");
        }

        void line(String indent, String text) {
            for (String part : clean(text).split("\n", -1)) {
                lines.add((PREFIX + indent + part).stripTrailing());
            }
        }

        void bullets(List<String> items, String whenEmpty) {
            if (items.isEmpty()) {
                line("  ", whenEmpty);
            }
            for (String item : items) {
                line("  ", "- " + item);
            }
        }

        String text() {
            return String.join("\n", lines) + "\n";
        }
    }
}
